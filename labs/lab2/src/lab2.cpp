void write_int(IFile &file, int n) {
    char c;
    int div = 1;
    if (n < 0) { file.write("-", 1); n = -n; }
    while (n / div >= 10) { div *= 10; }
    while (div > 0) {
        c = '0' + n / div;
        file.write(&c, 1);
        n %= div;
        div /= 10;
    }
}

